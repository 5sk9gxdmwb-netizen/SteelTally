"""Generate audited UI labels, or compare a native dump with observation evidence.

This handles labels/defaults only, not proprietary geometry or calculation code.
"""
import argparse
import json
from pathlib import Path


def literal(value):
    return "QStringLiteral(" + json.dumps(value, ensure_ascii=False) + ")"


def generate(observed, target):
    entries = []
    for name, entry in observed["catalogs"].items():
        assert sum(len(g["parts"]) for g in entry["groups"]) == entry["partCount"], name
        groups = []
        for group in entry["groups"]:
            parts = ", ".join(map(literal, group["parts"]))
            groups.append("            {" + literal(group["name"]) + ", {" + parts + "}}")
        entries.append(
            "        {" + literal(name) + ", {" + literal(entry["prefix"]) + ", "
            + literal(entry["fireLimit"]) + ", {\n"
            + ",\n".join(groups) + "\n        }}}"
        )
    header = (
        "#pragma once\n"
        "// Generated by tools/verified_catalog.py from normal GJG2026 UI observations.\n"
        "// Included within namespace partcatalog; Group and Qt types are already defined.\n"
        "// Scope: labels/order/new-row defaults only. No measurement algorithm claim.\n"
        "struct VerifiedEntry {\n"
        "    QString prefix, fireLimit;\n"
        "    QList<Group> groups;\n"
        "};\n"
        "inline const QMap<QString, VerifiedEntry>& verifiedCatalogue() {\n"
        "    static const QMap<QString, VerifiedEntry> data = {\n"
        + ",\n".join(entries)
        + "\n    };\n    return data;\n}\n"
    )
    target.write_text(header, encoding="utf-8")
    print(f"Generated {len(entries)} catalogues -> {target}")


def compare(observed, actual, categories=None):
    expected = observed["catalogs"]
    assert set(actual["catalogs"]) == set(expected), "Verified type coverage differs"
    total = 0
    for name, entry in expected.items():
        result = actual["catalogs"][name]
        for field in ("prefix", "fireLimit", "groups", "partCount"):
            assert result[field] == entry[field], f"{name}: {field} differs"
        total += entry["partCount"]
    assert actual["version"] == "1.0.2", "Unexpected native version"
    if categories:
        roots = actual["categories"]
        reference = categories["categories"]
        assert len(roots) == len(reference) == 6, "Category root count differs"
        for expected_group, actual_group in zip(reference, roots):
            assert expected_group["name"] == actual_group["name"], "Category order differs"
            if expected_group["name"] == "自定义":
                assert actual_group["types"] == categories["retainedCompatibleTypes"], "Compatible types lost"
            else:
                assert actual_group["types"] == expected_group["types"], expected_group["name"]
        print("PASS: six category groups / 34 reference types in observed order; five compatible types retained")
    print(f"PASS: native v{actual['version']}; {len(expected)} types, {total} items; "
          "group/order/prefix/defaults match independent live-UI evidence")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("observed", type=Path)
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument("--generate", type=Path)
    action.add_argument("--compare", type=Path)
    parser.add_argument("--categories", type=Path)
    args = parser.parse_args()
    observed = json.loads(args.observed.read_text(encoding="utf-8-sig"))
    if args.generate:
        generate(observed, args.generate)
    else:
        categories = json.loads(args.categories.read_text(encoding="utf-8-sig")) if args.categories else None
        compare(observed, json.loads(args.compare.read_text(encoding="utf-8-sig")), categories)


if __name__ == "__main__":
    main()
